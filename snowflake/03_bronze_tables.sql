-- File format, stage and bronze tables. Run as PIPELINE_ROLE.
-- Column names and order follow NHTSA's field description files (docs/nhtsa/*.txt).
-- Everything lands as VARCHAR; silver does the typing.
-- The bucket name comes from the Terraform output bucket_name.

USE ROLE PIPELINE_ROLE;
USE WAREHOUSE PIPELINE_WH;
USE SCHEMA VEHICLE_SAFETY.BRONZE;

-- Tab-delimited, no header row, UTF-8. Text fields contain literal double quotes and
-- backslashes, so quoting and escaping are both turned off. The pre-2010 recall file
-- has a few blank lines. Recalls use CRLF line endings, which the default handles.
CREATE FILE FORMAT IF NOT EXISTS NHTSA_TSV
  TYPE = CSV
  COMPRESSION = GZIP
  FIELD_DELIMITER = '\t'
  SKIP_HEADER = 0
  FIELD_OPTIONALLY_ENCLOSED_BY = NONE
  ESCAPE_UNENCLOSED_FIELD = NONE
  SKIP_BLANK_LINES = TRUE
  EMPTY_FIELD_AS_NULL = TRUE
  ENCODING = 'UTF8';

CREATE STAGE IF NOT EXISTS NHTSA_STAGE
  URL = 's3://vehicle-safety-lake-haosun/bronze/'
  STORAGE_INTEGRATION = NHTSA_S3
  FILE_FORMAT = NHTSA_TSV;

CREATE TABLE IF NOT EXISTS COMPLAINTS (
  CMPLID VARCHAR, ODINO VARCHAR, MFR_NAME VARCHAR, MAKETXT VARCHAR, MODELTXT VARCHAR,
  YEARTXT VARCHAR, CRASH VARCHAR, FAILDATE VARCHAR, FIRE VARCHAR, INJURED VARCHAR,
  DEATHS VARCHAR, COMPDESC VARCHAR, CITY VARCHAR, STATE VARCHAR, VIN VARCHAR,
  DATEA VARCHAR, LDATE VARCHAR, MILES VARCHAR, OCCURENCES VARCHAR, CDESCR VARCHAR,
  CMPL_TYPE VARCHAR, POLICE_RPT_YN VARCHAR, PURCH_DT VARCHAR, ORIG_OWNER_YN VARCHAR,
  ANTI_BRAKES_YN VARCHAR, CRUISE_CONT_YN VARCHAR, NUM_CYLS VARCHAR, DRIVE_TRAIN VARCHAR,
  FUEL_SYS VARCHAR, FUEL_TYPE VARCHAR, TRANS_TYPE VARCHAR, VEH_SPEED VARCHAR, DOT VARCHAR,
  TIRE_SIZE VARCHAR, LOC_OF_TIRE VARCHAR, TIRE_FAIL_TYPE VARCHAR, ORIG_EQUIP_YN VARCHAR,
  MANUF_DT VARCHAR, SEAT_TYPE VARCHAR, RESTRAINT_TYPE VARCHAR, DEALER_NAME VARCHAR,
  DEALER_TEL VARCHAR, DEALER_CITY VARCHAR, DEALER_STATE VARCHAR, DEALER_ZIP VARCHAR,
  PROD_TYPE VARCHAR, REPAIRED_YN VARCHAR, MEDICAL_ATTN VARCHAR, VEHICLES_TOWED_YN VARCHAR,
  STATE_OF_INCIDENT VARCHAR, VEHICLE_OPERATOR VARCHAR,
  _SOURCE_FILE VARCHAR, _LOADED_AT TIMESTAMP_LTZ
);

-- One table for both recall files; _SOURCE_FILE tells them apart.
CREATE TABLE IF NOT EXISTS RECALLS (
  RECORD_ID VARCHAR, CAMPNO VARCHAR, MAKETXT VARCHAR, MODELTXT VARCHAR, YEARTXT VARCHAR,
  MFGCAMPNO VARCHAR, COMPNAME VARCHAR, MFGNAME VARCHAR, BGMAN VARCHAR, ENDMAN VARCHAR,
  RCLTYPECD VARCHAR, POTAFF VARCHAR, ODATE VARCHAR, INFLUENCED_BY VARCHAR, MFGTXT VARCHAR,
  RCDATE VARCHAR, DATEA VARCHAR, RPNO VARCHAR, FMVSS VARCHAR, DESC_DEFECT VARCHAR,
  CONEQUENCE_DEFECT VARCHAR, CORRECTIVE_ACTION VARCHAR, NOTES VARCHAR, RCL_CMPT_ID VARCHAR,
  MFR_COMP_NAME VARCHAR, MFR_COMP_DESC VARCHAR, MFR_COMP_PTNO VARCHAR,
  DO_NOT_DRIVE VARCHAR, PARK_OUTSIDE VARCHAR,
  _SOURCE_FILE VARCHAR, _LOADED_AT TIMESTAMP_LTZ
);

