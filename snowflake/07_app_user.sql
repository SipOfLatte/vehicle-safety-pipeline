-- Read-only role and service user for the Streamlit app. Run as ACCOUNTADMIN.
-- Generate a separate key pair for the app (same commands as 06_service_user.sql, file app_reader_key.p8)
-- and paste its public key body in place of <PUBLIC_KEY>.
--
-- APP_ROLE can read the chatbot's documents, call Cortex to embed questions, read the load log for
-- the "data as of" line, and write only to its own usage table. It runs on APP_WH, whose resource
-- monitor caps app spend separately from the pipeline.

USE ROLE ACCOUNTADMIN;

CREATE SCHEMA IF NOT EXISTS VEHICLE_SAFETY.AI;
GRANT ALL ON SCHEMA VEHICLE_SAFETY.AI TO ROLE PIPELINE_ROLE;

CREATE ROLE IF NOT EXISTS APP_ROLE;
GRANT USAGE ON WAREHOUSE APP_WH TO ROLE APP_ROLE;
GRANT USAGE ON DATABASE VEHICLE_SAFETY TO ROLE APP_ROLE;
GRANT USAGE ON SCHEMA VEHICLE_SAFETY.AI TO ROLE APP_ROLE;
GRANT USAGE ON SCHEMA VEHICLE_SAFETY.BRONZE TO ROLE APP_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA VEHICLE_SAFETY.AI TO ROLE APP_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA VEHICLE_SAFETY.AI TO ROLE APP_ROLE;
GRANT SELECT ON TABLE VEHICLE_SAFETY.BRONZE.LOAD_LOG TO ROLE APP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE APP_ROLE;

-- Claude API spend per call, for the app's daily budget.
CREATE TABLE IF NOT EXISTS VEHICLE_SAFETY.AI.LLM_USAGE (
  CALLED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PURPOSE VARCHAR,
  MODEL VARCHAR,
  INPUT_TOKENS NUMBER,
  OUTPUT_TOKENS NUMBER,
  COST_USD FLOAT
);
GRANT SELECT, INSERT ON TABLE VEHICLE_SAFETY.AI.LLM_USAGE TO ROLE APP_ROLE;

CREATE USER IF NOT EXISTS APP_READER
  TYPE = SERVICE
  DEFAULT_ROLE = APP_ROLE
  DEFAULT_WAREHOUSE = APP_WH
  RSA_PUBLIC_KEY = '<PUBLIC_KEY>'
  COMMENT = 'Streamlit app';

GRANT ROLE APP_ROLE TO USER APP_READER;
