-- Service user for GitHub Actions: `dbt build` on pull requests into separate CI schemas.
-- Run as ACCOUNTADMIN. Generate a key pair for it (same commands as 06_service_user.sql, file
-- ci_dbt_key.p8) and paste its public key body in place of <PUBLIC_KEY>. The private key goes into
-- the GitHub Actions secret CI_SNOWFLAKE_PRIVATE_KEY, never into the repo.
--
-- CI_ROLE reads BRONZE and owns CI_SILVER, CI_GOLD and CI_AI (dbt's `ci` target writes to
-- CI_<schema>; see dbt/macros/generate_schema_name.sql). It can't touch the production SILVER,
-- GOLD or AI schemas. It uses PIPELINE_WH, so its spend counts against that warehouse's monitor.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS CI_ROLE;
GRANT USAGE ON WAREHOUSE PIPELINE_WH TO ROLE CI_ROLE;
GRANT USAGE ON DATABASE VEHICLE_SAFETY TO ROLE CI_ROLE;
GRANT USAGE ON SCHEMA VEHICLE_SAFETY.BRONZE TO ROLE CI_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA VEHICLE_SAFETY.BRONZE TO ROLE CI_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA VEHICLE_SAFETY.BRONZE TO ROLE CI_ROLE;

CREATE SCHEMA IF NOT EXISTS VEHICLE_SAFETY.CI_SILVER;
CREATE SCHEMA IF NOT EXISTS VEHICLE_SAFETY.CI_GOLD;
CREATE SCHEMA IF NOT EXISTS VEHICLE_SAFETY.CI_AI;
GRANT OWNERSHIP ON SCHEMA VEHICLE_SAFETY.CI_SILVER TO ROLE CI_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA VEHICLE_SAFETY.CI_GOLD TO ROLE CI_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA VEHICLE_SAFETY.CI_AI TO ROLE CI_ROLE COPY CURRENT GRANTS;

CREATE USER IF NOT EXISTS CI_DBT
  TYPE = SERVICE
  DEFAULT_ROLE = CI_ROLE
  DEFAULT_WAREHOUSE = PIPELINE_WH
  DEFAULT_SECONDARY_ROLES = ()
  RSA_PUBLIC_KEY = '<PUBLIC_KEY>'
  COMMENT = 'GitHub Actions dbt build on pull requests';

GRANT ROLE CI_ROLE TO USER CI_DBT;

-- Check: USAGE on PIPELINE_WH, VEHICLE_SAFETY and BRONZE, SELECT on the BRONZE tables, OWNERSHIP of the CI schemas.
SHOW GRANTS TO ROLE CI_ROLE;
