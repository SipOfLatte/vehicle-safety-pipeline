-- Run once in Snowsight as ACCOUNTADMIN, before anything else.
-- Warehouses, spend limits, database, schemas and the pipeline role.

USE ROLE ACCOUNTADMIN;

-- Spend limits first. Quotas are in credits per calendar month.
-- The account monitor covers all warehouses; APP_WH has its own smaller one so
-- public app traffic can't use up the pipeline's credits.
-- Resource monitors only cover warehouse compute. Cortex embedding calls are billed as
-- serverless AI credits and need a Snowflake budget (Admin > Cost management) instead.
CREATE RESOURCE MONITOR IF NOT EXISTS ACCOUNT_MONITOR
  WITH CREDIT_QUOTA = 6
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER ACCOUNT SET RESOURCE_MONITOR = ACCOUNT_MONITOR;

CREATE RESOURCE MONITOR IF NOT EXISTS APP_WH_MONITOR
  WITH CREDIT_QUOTA = 3
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;

CREATE WAREHOUSE IF NOT EXISTS PIPELINE_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE WAREHOUSE IF NOT EXISTS APP_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  RESOURCE_MONITOR = APP_WH_MONITOR;

CREATE DATABASE IF NOT EXISTS VEHICLE_SAFETY;
CREATE SCHEMA IF NOT EXISTS VEHICLE_SAFETY.BRONZE;
CREATE SCHEMA IF NOT EXISTS VEHICLE_SAFETY.SILVER;
CREATE SCHEMA IF NOT EXISTS VEHICLE_SAFETY.GOLD;

-- Role for ingestion, COPY and dbt. The read-only app role comes in week 5.
CREATE ROLE IF NOT EXISTS PIPELINE_ROLE;
GRANT USAGE, OPERATE ON WAREHOUSE PIPELINE_WH TO ROLE PIPELINE_ROLE;
GRANT USAGE ON DATABASE VEHICLE_SAFETY TO ROLE PIPELINE_ROLE;
GRANT ALL ON SCHEMA VEHICLE_SAFETY.BRONZE TO ROLE PIPELINE_ROLE;
GRANT ALL ON SCHEMA VEHICLE_SAFETY.SILVER TO ROLE PIPELINE_ROLE;
GRANT ALL ON SCHEMA VEHICLE_SAFETY.GOLD TO ROLE PIPELINE_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE PIPELINE_ROLE;
GRANT ROLE PIPELINE_ROLE TO ROLE SYSADMIN;

-- Your Snowflake user name from SHOW USERS. It's stored in lowercase, so it needs double quotes.
GRANT ROLE PIPELINE_ROLE TO USER "<your_user_name>";
